// Writes cases.inc for test_htmb.c from documentation/test-cases.json and html.json:
//
//   node c/tests/generate_cases.js
//
// Each case becomes a real macro call, so the generated tag macros are what gets tested.
const fs = require("fs");
const path = require("path");

const docs = path.join(__dirname, "..", "..", "documentation");
const { cases } = require(path.join(docs, "test-cases.json"));
const html = require(path.join(docs, "html.json"));

// JSON strings double as C string literals, as long as they stay printable ASCII
const str = (s) => {
  if (!/^[\x20-\x7e]*$/.test(s)) throw new Error(`not printable ASCII: ${JSON.stringify(s)}`);
  return JSON.stringify(s);
};
const cap = (tag) => tag[0].toUpperCase() + tag.slice(1);

function call(c) {
  if ("escape" in c) return `htmb_escape(${str(c.escape)})`;

  const attrs = (c.attrs || []).map(([name, value]) => str(value === undefined ? name : `${name}=${value}`));
  const kids = (c.children || []).map(str);
  const name = cap(c.tag);

  if (html.tagsVoid.includes(c.tag)) {
    if (kids.length) throw new Error(`${c.name}: void tags can't have children`);
    return attrs.length ? `${name}Attr((${attrs.join(", ")}))` : `${name}()`;
  }
  if (!attrs.length) return `${name}(${kids.join(", ")})`;
  return `${name}Attr((${attrs.join(", ")})${kids.map((k) => `, ${k}`).join("")})`;
}

const lines = [
  "/* Generated by generate_cases.js from documentation/test-cases.json and html.json; don't edit. */",
  ...cases.map((c) => `expect(${str(c.name)}, ${call(c)}, ${str(c.html)});`),
  ...html.tags.map((tag) => `expect(${str(`tag ${tag}`)}, ${cap(tag)}(), ${str(`<${tag}></${tag}>`)});`),
  ...html.tagsVoid.map((tag) => `expect(${str(`tag ${tag}`)}, ${cap(tag)}(), ${str(`<${tag}/>`)});`),
];

const out = path.join(__dirname, "cases.inc");
fs.writeFileSync(out, lines.join("\n") + "\n");
console.log(`${out}: ${cases.length} cases, ${html.tags.length + html.tagsVoid.length} tags`);
