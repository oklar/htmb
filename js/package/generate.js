// Regenerates the tag lists in index.js and index.d.ts from
// documentation/html.json, then rebuilds htmb.umd.js and index.mjs from index.js:
//
//   node js/package/generate.js
const fs = require("fs");
const path = require("path");

const html = require("../../documentation/html.json");
const indexPath = path.join(__dirname, "index.js");
const typesPath = path.join(__dirname, "index.d.ts");
const umdPath = path.join(__dirname, "htmb.umd.js");
const esmPath = path.join(__dirname, "index.mjs");

const beginMarker = "// tags below are generated";
const endMarker = "// end of generated tags";
const exportsMarker = "// CommonJS exports";

// work with \n, and write each file back with its own line endings
const read = (file) => fs.readFileSync(file, "utf8");
const write = (file, text, crlf) =>
  fs.writeFileSync(file, crlf ? text.replace(/\n/g, "\r\n") : text);
const writeBuilt = (file, text) =>
  write(file, text, fs.existsSync(file) && read(file).includes("\r\n"));

// Replaces the lines between the markers in file, and returns the new text
function writeTags(file, generated) {
  const original = read(file);
  const text = original.replace(/\r\n/g, "\n");

  const begin = text.indexOf(beginMarker);
  const end = text.indexOf(endMarker);
  if (begin < 0 || end < begin) {
    throw new Error(`${file}: missing generated-tags markers`);
  }

  const result =
    text.slice(0, text.indexOf("\n", begin) + 1) +
    generated +
    text.slice(text.lastIndexOf("\n", end) + 1);
  write(file, result, original.includes("\r\n"));
  return result;
}

const list = (name, tags) =>
  `const ${name} = [\n${tags.map((tag) => `  "${tag}",\n`).join("")}];\n`;

const index = writeTags(
  indexPath,
  list("tagsVoid", html.tagsVoid) + "\n" + list("tags", html.tags)
);
if (index.indexOf(exportsMarker) < index.indexOf(endMarker)) {
  throw new Error(`${indexPath}: missing exports marker below the tags`);
}

const members = (tags) =>
  tags.map((tag) => `    ${tag}: TagFunction;\n`).join("");

writeTags(typesPath, members(html.tagsVoid) + "\n" + members(html.tags));

// htmb.umd.js and index.mjs are index.js from the tag lists down to the
// CommonJS exports
const core = index
  .slice(index.indexOf(beginMarker), index.indexOf(exportsMarker))
  .trimEnd();

// htmb.umd.js wraps it so it also works with AMD and as a browser global
const umd = `// Generated by generate.js from index.js; edit index.js instead.
(function (root, factory) {
  if (typeof define === "function" && define.amd) {
    // AMD
    define([], factory);
  } else if (typeof exports === "object") {
    // CommonJS
    module.exports = factory();
  } else {
    // Browser global
    root.htmb = factory();
  }
})(typeof self !== "undefined" ? self : this, function () {
${core
  .split("\n")
  .map((line) => (line ? `  ${line}` : line))
  .join("\n")}

  return htmb;
});
`;
writeBuilt(umdPath, umd);

// index.mjs is an ES module, so bundlers can use it without Node's "module".
// It also exports each tag and escape by name. A tag that's a reserved word,
// like var, can't be a variable, so it's exported from one with another name.
const isVariableName = (name) => {
  try {
    new Function(`"use strict"; let ${name};`);
    return true;
  } catch {
    return false;
  }
};
const allTags = [...html.tagsVoid, ...html.tags];
const renamed = allTags.filter((tag) => !isVariableName(tag));

const esm = `// Generated by generate.js from index.js; edit index.js instead.
${core}

export default htmb;

export const {
${allTags
  .filter(isVariableName)
  .map((tag) => `  ${tag},\n`)
  .join("")}} = htmb;

${renamed.map((tag) => `const ${tag}Tag = htmb.${tag};\n`).join("")}export {
${renamed.map((tag) => `  ${tag}Tag as ${tag},\n`).join("")}  escape,
};
`;
writeBuilt(esmPath, esm);

console.log(
  `${indexPath}, ${typesPath}: ${html.tags.length} tags, ${html.tagsVoid.length} void tags; rebuilt ${umdPath} and ${esmPath}`
);
