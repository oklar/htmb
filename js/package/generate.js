// Regenerates the tag lists in index.js from documentation/html.json, then
// rebuilds htmb.umd.js from index.js:
//
//   node js/package/generate.js
const fs = require("fs");
const path = require("path");

const html = require("../../documentation/html.json");
const indexPath = path.join(__dirname, "index.js");
const umdPath = path.join(__dirname, "htmb.umd.js");

const beginMarker = "// tags below are generated";
const endMarker = "// end of generated tags";
const exportsMarker = "// CommonJS exports";

// work with \n, and write each file back with its own line endings
const read = (file) => fs.readFileSync(file, "utf8");
const write = (file, text, crlf) =>
  fs.writeFileSync(file, crlf ? text.replace(/\n/g, "\r\n") : text);

const original = read(indexPath);
let index = original.replace(/\r\n/g, "\n");

const begin = index.indexOf(beginMarker);
const end = index.indexOf(endMarker);
if (begin < 0 || end < begin || index.indexOf(exportsMarker) < end) {
  throw new Error(`${indexPath}: missing generated-tags or exports markers`);
}

const list = (name, tags) =>
  `const ${name} = [\n${tags.map((tag) => `  "${tag}",\n`).join("")}];\n`;

index =
  index.slice(0, index.indexOf("\n", begin) + 1) +
  list("tagsVoid", html.tagsVoid) +
  "\n" +
  list("tags", html.tags) +
  index.slice(index.lastIndexOf("\n", end) + 1);
write(indexPath, index, original.includes("\r\n"));

// htmb.umd.js is index.js from the tag lists down to the CommonJS exports,
// wrapped so it also works with AMD and as a browser global
const core = index
  .slice(index.indexOf(beginMarker), index.indexOf(exportsMarker))
  .trimEnd()
  .split("\n")
  .map((line) => (line ? `  ${line}` : line))
  .join("\n");

const umd = `// Generated by generate.js from index.js; edit index.js instead.
(function (root, factory) {
  if (typeof define === "function" && define.amd) {
    // AMD
    define([], factory);
  } else if (typeof exports === "object") {
    // CommonJS
    module.exports = factory();
  } else {
    // Browser global
    root.htmb = factory();
  }
})(typeof self !== "undefined" ? self : this, function () {
${core}

  return htmb;
});
`;
write(umdPath, umd, fs.existsSync(umdPath) && read(umdPath).includes("\r\n"));

console.log(
  `${indexPath}: ${html.tags.length} tags, ${html.tagsVoid.length} void tags; rebuilt ${umdPath}`
);
